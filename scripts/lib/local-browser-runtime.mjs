// Local execution base for the browser driver.
//
// The driver was written for a container box that ships a `box-chrome` command,
// owns a desktop per agent window, and has playwright-core inside /workspace.
// The WSL build has none of those: there is one Xvfb display (the one
// computer-use already owns) and a box workspace on the user's own disk. This
// module provisions the two missing pieces so the shipped driver runs unchanged
// — a box-chrome shim on PATH, and playwright-core resolvable from /workspace.
import { constants } from "node:fs";
import { access, chmod, lstat, mkdir, readlink, symlink, unlink, writeFile } from "node:fs/promises";
import { delimiter, join } from "node:path";

/** Mirrors SAND_BROWSER_DRIVER_BOX_DIR; the launcher cannot import host TypeScript. */
export const DRIVER_BOX_DIR = "/tmp/.sand-browser";

export const BOX_CDP_PORT_BASE = 9222;
export const LOCAL_BROWSER_WINDOW_SIZE = { width: 1440, height: 900 };

const CHROME_CANDIDATES = [
  "/usr/bin/google-chrome",
  "/usr/bin/google-chrome-stable",
  "/usr/bin/chromium",
  "/usr/bin/chromium-browser",
  "/snap/bin/chromium",
];

async function isExecutable(path) {
  try {
    await access(path, constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

export async function resolveChromeBinary(candidates = CHROME_CANDIDATES) {
  for (const candidate of candidates) {
    if (await isExecutable(candidate)) return candidate;
  }
  return undefined;
}

/**
 * The shim the driver's `spawn("box-chrome", ["--new-window"])` lands on.
 *
 * The driver passes the agent's window only as DISPLAY and then expects CDP on
 * BOX_CDP_PORT_BASE + that window number, so the port is derived from DISPLAY
 * here rather than passed in — the two must not be able to disagree. The window
 * size is fixed because the driver reports element boxes in viewport
 * coordinates and screenshots feed auto-review; a size that changes with
 * whatever the window manager felt like would make both non-reproducible.
 */
export function boxChromeShimScript({ chromeBinary, profileDir, portBase = BOX_CDP_PORT_BASE, windowSize = LOCAL_BROWSER_WINDOW_SIZE }) {
  if (typeof chromeBinary !== "string" || chromeBinary.length === 0) {
    throw new Error("boxChromeShimScript needs a chromeBinary path");
  }
  if (typeof profileDir !== "string" || profileDir.length === 0) {
    throw new Error("boxChromeShimScript needs a profileDir path");
  }
  return `#!/bin/sh
# Generated by Belmont's launcher. The browser driver spawns "box-chrome" with
# DISPLAY set to the agent's window and then connects to CDP on ${portBase} + that
# window number, so the port is derived from DISPLAY and cannot drift from it.
set -eu
window=\${DISPLAY#:}
window=\${window%%.*}
case "$window" in
  ''|*[!0-9]*) window=0 ;;
esac
port=$((${portBase} + window))
profile='${profileDir}'
mkdir -p "$profile"
exec '${chromeBinary}' \\
  --remote-debugging-port="$port" \\
  --remote-debugging-address=127.0.0.1 \\
  --user-data-dir="$profile" \\
  --window-size=${windowSize.width},${windowSize.height} \\
  --no-first-run \\
  --no-default-browser-check \\
  --disable-background-networking \\
  --disable-features=Translate,MediaRouter \\
  "$@"
`;
}

/** Prepends dir to a PATH value without duplicating an entry that is already first. */
export function prependPath(pathValue, dir) {
  const entries = (pathValue ?? "").split(delimiter).filter((entry) => entry.length > 0);
  if (entries[0] === dir) return entries.join(delimiter);
  return [dir, ...entries.filter((entry) => entry !== dir)].join(delimiter);
}

/**
 * Writes the box-chrome shim and reports what the browser stack is still
 * missing. Provisioning never throws for a missing dependency: the host gates
 * the browser tools on the same readiness, and a launcher that dies because
 * Chrome is absent would take the whole app with it.
 */
export async function ensureLocalBrowserRuntime({
  binDir,
  profileDir,
  workspaceDir,
  driverDir = DRIVER_BOX_DIR,
  chromeBinary,
  log = () => {},
}) {
  const missing = [];
  const chrome = chromeBinary ?? (await resolveChromeBinary());
  if (chrome === undefined) {
    missing.push("google-chrome");
    log("[local-browser] no Chrome binary found; browser tools stay off");
  } else {
    await mkdir(binDir, { recursive: true });
    const shimPath = join(binDir, "box-chrome");
    await writeFile(shimPath, boxChromeShimScript({ chromeBinary: chrome, profileDir }), "utf8");
    await chmod(shimPath, 0o755);
    log(`[local-browser] box-chrome -> ${chrome} (profile ${profileDir})`);
  }
  // The driver imports playwright-core as a bare specifier, and ESM resolves
  // those from the importing FILE's directory — not the working directory the
  // shell was given. The driver is uploaded to driverDir, so a package installed
  // in the box workspace is invisible to it; link the workspace's node_modules
  // next to the driver instead.
  await mkdir(driverDir, { recursive: true });
  const linkPath = join(driverDir, "node_modules");
  await linkWorkspaceModules(linkPath, join(workspaceDir, "node_modules"));
  const playwrightPath = join(linkPath, "playwright-core", "package.json");
  try {
    await access(playwrightPath, constants.R_OK);
  } catch {
    missing.push("playwright-core");
    log(`[local-browser] playwright-core is not reachable at ${playwrightPath}; browser tools stay off`);
  }
  return { binDir, chromeBinary: chrome, driverDir, missing };
}

/**
 * Points linkPath at target, leaving a real directory alone — someone may have
 * installed packages next to the driver directly, and replacing that with a link
 * would silently drop them.
 */
export async function linkWorkspaceModules(linkPath, target) {
  const existing = await lstat(linkPath).catch(() => undefined);
  if (existing !== undefined && !existing.isSymbolicLink()) return "kept-directory";
  if (existing !== undefined) {
    if ((await readlink(linkPath).catch(() => undefined)) === target) return "already-linked";
    await unlink(linkPath);
  }
  await symlink(target, linkPath, "dir");
  return "linked";
}
