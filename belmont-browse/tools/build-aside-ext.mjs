#!/usr/bin/env node
// belmont-browse: build a loadable copy of the original "Aside Browsing Agent" extension (our code).
// The original targets Aside's Chromium fork, which adds private chrome.aside* APIs and seven private
// permissions. This copy strips the private permissions and injects aside-shim.js, which supplies the
// handful of private calls the extension actually makes (13 across its bundles): profile identity, the
// daemon auth challenge signature (P-256 key from src/daemon-server.mjs), notification permission, mini
// popup window control and two browser preferences. Everything else it uses is standard Chrome API.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { ensureInstallationKeys } from "../src/daemon-server.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.env.ASIDE_EXT_SRC || path.join(ROOT, "vendor", "aside-ext", "AsideAgentManager");
const OUT = process.env.ASIDE_EXT_OUT || path.join(ROOT, ".state", "aside-ext");
const PROFILE_DIR = process.env.BELMONT_BROWSE_PROFILE_DIR || path.join(ROOT, ".state", "chrome-profile");
const PROFILE_ID = process.env.ASIDE_EXT_PROFILE_ID || "belmont-ui";
const BOUND_ACCOUNT_ID = Number(process.env.ASIDE_EXT_ACCOUNT_ID || 0);

if (!existsSync(path.join(SRC, "manifest.json"))) throw new Error(`extension source missing: ${SRC}`);
const keys = ensureInstallationKeys(path.join(ROOT, ".state"));
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
cpSync(SRC, OUT, { recursive: true, filter: (p) => !p.includes(":com.apple.provenance") });

// Bind the copied omnibox consumers to the native result generation before any
// shim or manifest changes. The patcher accepts only pinned original/output bytes.
execFileSync("python3", [path.join(ROOT, "tools", "patch-omnibox-generation.py"), "--assets", path.join(OUT, "assets")], { stdio: "inherit" });

// 1. manifest: drop the fork-only permissions (stock Chrome refuses unknown permission names).
const manifest = JSON.parse(readFileSync(path.join(OUT, "manifest.json"), "utf8"));
const dropped = manifest.permissions.filter((p) => p.startsWith("at.studio."));
manifest.permissions = manifest.permissions.filter((p) => !p.startsWith("at.studio."));
manifest.name = `${manifest.name} (Belmont)`;
writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

// 2. the shim: private APIs the bundles call, backed by our installation key and profile record.
const profile = { profileId: PROFILE_ID, profilePath: PROFILE_DIR, profileIndex: 0, boundAccountId: BOUND_ACCOUNT_ID };
const shim = `// belmont-browse aside-shim: stands in for Aside's fork-only chrome.aside* APIs (generated by tools/build-aside-ext.mjs)
(() => {
  if (typeof chrome === "undefined") return;
  const PRIVATE_JWK = ${JSON.stringify(keys.privateJwk)};
  const PROFILE = ${JSON.stringify(profile)};
  const PREFIX = new TextEncoder().encode("Aside Daemon Auth v1\\0");
  const fromB64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
  const toB64 = (u8) => { let s = ""; for (const b of u8) s += String.fromCharCode(b); return btoa(s); };
  const derInt = (u8) => { let i = 0; while (i < u8.length - 1 && u8[i] === 0) i++; let v = u8.subarray(i); if (v[0] & 0x80) v = new Uint8Array([0, ...v]); return new Uint8Array([0x02, v.length, ...v]); };
  const rawToDer = (raw) => { const r = derInt(raw.subarray(0, 32)), s = derInt(raw.subarray(32, 64)); return new Uint8Array([0x30, r.length + s.length, ...r, ...s]); };
  let keyPromise;
  const key = () => (keyPromise ??= crypto.subtle.importKey("jwk", PRIVATE_JWK, { name: "ECDSA", namedCurve: "P-256" }, false, ["sign"]));
  const sign = async (arg) => {
    const challenge = typeof arg === "string" ? arg : arg?.challenge;
    let input = arg && typeof arg === "object" && arg.signingInput instanceof Uint8Array ? arg.signingInput : null;
    if (!input) { const c = fromB64(challenge); input = new Uint8Array(PREFIX.length + c.length); input.set(PREFIX, 0); input.set(c, PREFIX.length); }
    const raw = new Uint8Array(await crypto.subtle.sign({ name: "ECDSA", hash: "SHA-256" }, await key(), input));
    return { signedChallenge: toB64(rawToDer(raw)) };
  };
  chrome.asideAccount ??= {
    getProfileContext: async () => ({ ...PROFILE }),
    getProfiles: async () => [{ ...PROFILE, name: "Belmont", displayName: "Belmont", isCurrent: true }],
    signDaemonAuthChallenge: sign,
  };
  chrome.asideNotification ??= { requestPermission: async () => ({ granted: true }), revokePermission: async () => ({}) };
  chrome.asideMiniPopup ??= { setState: () => {}, setSize: () => {}, hide: () => { try { window.close(); } catch {} }, pickDirectory: async () => null, switchProfile: async () => {} };
  chrome.asideBrowserPreferences ??= {
    getAutoPipEnabled: async () => false, setAutoPipEnabled: async () => {},
    getHorizontalTabShrinkEnabled: async () => false, setHorizontalTabShrinkEnabled: async () => {},
  };
  chrome.asideOmnibox ??= {}; chrome.asideBrowserImport ??= {};
})();
`;
writeFileSync(path.join(OUT, "aside-shim.js"), shim);

// 3. inject it first in every extension context: the module service worker and each HTML page.
const bg = readFileSync(path.join(OUT, "background.js"), "utf8");
writeFileSync(path.join(OUT, "background.js"), `import "./aside-shim.js";\n${bg}`);
let pages = 0;
for (const name of readdirSync(OUT)) {
  if (!name.endsWith(".html")) continue;
  const html = readFileSync(path.join(OUT, name), "utf8");
  const injected = html.includes("<head>") ? html.replace("<head>", '<head><script src="./aside-shim.js"></script>') : `<script src="./aside-shim.js"></script>\n${html}`;
  writeFileSync(path.join(OUT, name), injected); pages += 1;
}
// 4. the page bundles enforce a CSP from the manifest; make sure our classic script is allowed (extension pages allow 'self').
console.log(`[build-aside-ext] ${OUT}: ${manifest.name} ${manifest.version}; dropped ${dropped.length} private permissions; shim injected into background.js + ${pages} pages; profile ${PROFILE_ID} → account ${BOUND_ACCOUNT_ID}; key ${keys.publicRawBase64.slice(0, 12)}…`);
